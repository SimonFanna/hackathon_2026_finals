-- Synthetic "small bank": the raw facts KBC could plausibly observe about a customer.
-- 100% synthetic, produced by scripts/bank_data/generate.py. No real person, account or identifier.
--
-- Layering (see backend/backend.md): these tables hold FACTS only (profile, products,
-- transactions, in-app events). Signals, moments, intents and journeys are derived by the
-- backend / ML and live in their own tables. The life moment each customer is really in
-- (the ground truth used to train and evaluate models) lives in the private `ml` schema,
-- which is not exposed through the Data API.
--
-- Access: RLS is on everywhere. anon / authenticated can read only the demo personas
-- (customers.is_demo); the full bank is read server-side with the secret key.

-- ---------------------------------------------------------------- customers & household

create table public.customers (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  birth_date date not null,
  gender text not null check (gender in ('f', 'm', 'x')),
  language text not null check (language in ('nl', 'fr', 'en')),
  email text not null unique,                 -- always @example.com (reserved domain)
  postal_code text not null,
  city text not null,
  region text not null check (region in ('flanders', 'wallonia', 'brussels')),
  marital_status text not null check (marital_status in ('single', 'cohabiting', 'married', 'divorced', 'widowed')),
  segment text not null check (segment in ('private', 'self_employed', 'business_owner')),
  customer_since date not null,
  is_demo boolean not null default false,
  demo_slug text unique,                      -- stable handle for the UI, e.g. 'sofie'
  check (is_demo = (demo_slug is not null))
);

create table public.customer_children (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers (id) on delete cascade,
  first_name text not null,
  birth_date date not null
);
create index customer_children_customer_id_idx on public.customer_children (customer_id);

-- One row per customer: current situation.
create table public.customer_employment (
  customer_id bigint primary key references public.customers (id) on delete cascade,
  status text not null check (status in ('employee', 'self_employed', 'business_owner', 'job_seeker', 'student', 'retired')),
  sector text,
  employer_name text,                         -- synthetic company name, null when not employed
  company_name text,                          -- own company (self_employed / business_owner)
  company_vat text,                           -- synthetic BE0xxxxxxxxx, never a real number
  company_founded_on date,
  monthly_net_income_eur numeric(10, 2) not null check (monthly_net_income_eur >= 0),
  since date not null
);

-- Homes the customer owns (known to the bank through a home loan or insurance file).
create table public.properties (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers (id) on delete cascade,
  kind text not null check (kind in ('house', 'apartment')),
  build_year int not null check (build_year between 1850 and 2030),
  epc_label text check (epc_label in ('A+', 'A', 'B', 'C', 'D', 'E', 'F')),
  estimated_value_eur numeric(12, 2) not null,
  postal_code text not null,
  acquired_on date not null
);
create index properties_customer_id_idx on public.properties (customer_id);

-- Housing situation as the bank knows it.
create table public.customer_housing (
  customer_id bigint primary key references public.customers (id) on delete cascade,
  status text not null check (status in ('owner', 'tenant', 'with_parents')),
  monthly_rent_eur numeric(10, 2) check (monthly_rent_eur >= 0)
);

-- ---------------------------------------------------------------- products

create table public.accounts (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers (id) on delete cascade,
  ecosystem_item_id bigint references public.ecosystem_items (id),
  kind text not null check (kind in ('current', 'savings', 'business_current', 'term_deposit')),
  iban text not null unique,                  -- synthetic, BE-formatted, not a real account
  opened_on date not null,
  balance_eur numeric(14, 2) not null         -- balance at the end of the simulated period
);
create index accounts_customer_id_idx on public.accounts (customer_id);
create index accounts_ecosystem_item_id_idx on public.accounts (ecosystem_item_id);

create table public.loans (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers (id) on delete cascade,
  ecosystem_item_id bigint references public.ecosystem_items (id),
  kind text not null check (kind in ('home', 'renovation', 'energy', 'car', 'personal', 'business_investment')),
  principal_eur numeric(12, 2) not null check (principal_eur > 0),
  annual_rate_pct numeric(5, 3) not null check (annual_rate_pct >= 0),
  term_months int not null check (term_months > 0),
  monthly_payment_eur numeric(10, 2) not null,
  start_date date not null,
  end_date date not null,
  outstanding_eur numeric(12, 2) not null check (outstanding_eur >= 0),
  status text not null check (status in ('active', 'repaid')),
  check (end_date > start_date)
);
create index loans_customer_id_idx on public.loans (customer_id);
create index loans_ecosystem_item_id_idx on public.loans (ecosystem_item_id);

-- Every other product held: insurance, cards, pension, investing, digital services…
create table public.product_holdings (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers (id) on delete cascade,
  ecosystem_item_id bigint not null references public.ecosystem_items (id),
  since date not null,
  monthly_premium_eur numeric(10, 2),         -- insurance / pension / investment plan, if any
  status text not null default 'active' check (status in ('active', 'cancelled')),
  unique (customer_id, ecosystem_item_id)
);
create index product_holdings_ecosystem_item_id_idx on public.product_holdings (ecosystem_item_id);

-- ---------------------------------------------------------------- behaviour

create table public.transactions (
  id bigint generated by default as identity primary key,
  account_id bigint not null references public.accounts (id) on delete cascade,
  customer_id bigint not null references public.customers (id) on delete cascade,
  booked_on date not null,
  amount_eur numeric(12, 2) not null check (amount_eur <> 0),   -- negative = money out
  category text not null check (category in (
    'salary', 'freelance_income', 'benefits', 'pension_income', 'transfer_in',
    'rent', 'mortgage_payment', 'loan_payment', 'groceries', 'energy_utilities', 'telecom',
    'fuel', 'ev_charging', 'public_transport', 'car_maintenance', 'restaurants', 'shopping',
    'baby_kids', 'childcare_school', 'health', 'insurance_premium', 'subscriptions', 'travel',
    'home_improvement', 'furniture', 'electronics', 'business_supplies', 'accounting_software',
    'notary', 'taxes', 'savings_transfer', 'investment', 'cash_withdrawal', 'other')),
  counterparty text not null,                 -- synthetic merchant / payer name
  description text
);
create index transactions_customer_id_booked_on_idx on public.transactions (customer_id, booked_on);
create index transactions_account_id_idx on public.transactions (account_id);

-- What the customer did inside KBC Mobile / KBC Touch / Kate.
create table public.app_events (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers (id) on delete cascade,
  session_id text not null,
  occurred_at timestamptz not null,
  channel text not null check (channel in ('kbc_mobile', 'kbc_touch', 'kate')),
  event_type text not null check (event_type in (
    'page_view', 'simulation', 'search', 'kate_question', 'application_started', 'application_completed')),
  ecosystem_item_id bigint references public.ecosystem_items (id),   -- the service consulted, if any
  detail jsonb not null default '{}'::jsonb   -- e.g. {"amount": 320000} or {"query": "solar panels"}
);
create index app_events_customer_id_occurred_at_idx on public.app_events (customer_id, occurred_at);
create index app_events_ecosystem_item_id_idx on public.app_events (ecosystem_item_id);

-- ---------------------------------------------------------------- ground truth (private)

create schema if not exists ml;
revoke all on schema ml from public, anon, authenticated;

-- The latent persona and life moment the generator assigned. The app never reads this:
-- models must infer it from the facts above. Used only to train and evaluate.
create table ml.customer_truth (
  customer_id bigint primary key references public.customers (id) on delete cascade,
  persona text not null,
  life_moment text not null check (life_moment in (
    'buy_house', 'start_business', 'new_parent', 'buy_ev', 'prepare_retirement', 'none')),
  moment_started_on date,
  converted boolean not null default false,   -- took the anchor product before the period ended
  check ((life_moment = 'none') = (moment_started_on is null))
);
alter table ml.customer_truth enable row level security;
revoke all on all tables in schema ml from public, anon, authenticated;

