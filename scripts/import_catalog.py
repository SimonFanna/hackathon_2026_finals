"""Turn resources/KBC_Ecosystems.xlsx into an idempotent SQL seed and a JSON copy.

Usage: python3 scripts/import_catalog.py [xlsx] [out.sql]
Defaults: resources/KBC_Ecosystems.xlsx -> supabase/seed/catalog.sql
          and web/src/backend/data/snapshot/catalogue.json (offline copy for the backend).
"""

import json
import re
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
PARTNER_HUB = "Partner Hub"


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def split_label(label: str) -> tuple[str, str | None, bool]:
    """'Car sharing - Cambio' -> ('Car sharing', 'Cambio', False)."""
    if " - " not in label:
        return label, None, False
    name, suffix = label.rsplit(" - ", 1)
    if suffix == PARTNER_HUB:
        return name, None, True
    return name, suffix, False


def read_rows(xlsx: Path) -> list[tuple[int, str, str]]:
    sheet = openpyxl.load_workbook(xlsx, data_only=True).worksheets[0]
    rows = []
    for idx, (ecosystem, label) in enumerate(sheet.iter_rows(min_row=2, values_only=True), start=2):
        if ecosystem is None and label is None:
            continue
        rows.append((idx, str(ecosystem).strip(), str(label).strip()))
    return rows


def build_sql(rows: list[tuple[int, str, str]]) -> str:
    ecosystems = list(dict.fromkeys(eco for _, eco, _ in rows))
    items = [(row, eco, label, *split_label(label)) for row, eco, label in rows]
    partners = sorted({p for *_, p, _ in items if p})

    out = ["-- Generated by scripts/import_catalog.py — do not edit by hand.", "begin;", ""]

    out.append("insert into public.ecosystems (name, slug, position) values")
    out.append(",\n".join(f"  ({q(e)}, {q(slugify(e))}, {i})" for i, e in enumerate(ecosystems, 1)))
    out.append("on conflict (name) do nothing;\n")

    out.append("insert into public.partners (name) values")
    out.append(",\n".join(f"  ({q(p)})" for p in partners))
    out.append("on conflict (name) do nothing;\n")

    out.append("insert into public.ecosystem_items")
    out.append("  (source_row, ecosystem_id, partner_id, name, raw_label, via_partner_hub)")
    out.append("select v.source_row, e.id, p.id, v.name, v.raw_label, v.via_partner_hub")
    out.append("from (values")
    out.append(",\n".join(
        f"  ({row}, {q(eco)}, {q(partner) if partner else 'null'}, {q(name)}, {q(label)}, {str(hub).lower()})"
        for row, eco, label, name, partner, hub in items
    ))
    out.append(") as v (source_row, ecosystem, partner, name, raw_label, via_partner_hub)")
    out.append("join public.ecosystems e on e.name = v.ecosystem")
    out.append("left join public.partners p on p.name = v.partner")
    out.append("on conflict (source_row) do nothing;\n")

    out.append("commit;")
    return "\n".join(out) + "\n"


def build_json(rows: list[tuple[int, str, str]]) -> str:
    items = []
    for row, eco, label in rows:
        name, partner, hub = split_label(label)
        items.append({"sourceRow": row, "ecosystem": eco, "name": name, "partner": partner, "viaPartnerHub": hub})
    return json.dumps(items, indent=1, ensure_ascii=False) + "\n"


def main() -> None:
    xlsx = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "resources" / "KBC_Ecosystems.xlsx"
    dest = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "supabase" / "seed" / "catalog.sql"
    rows = read_rows(xlsx)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(build_sql(rows))
    print(f"{len(rows)} rows -> {dest}")
    json_dest = ROOT / "web" / "src" / "backend" / "data" / "snapshot" / "catalogue.json"
    json_dest.parent.mkdir(parents=True, exist_ok=True)
    json_dest.write_text(build_json(rows))
    print(f"{len(rows)} rows -> {json_dest}")


if __name__ == "__main__":
    main()
