"""web/src/backend/fixtures/t1-signal-rules.json → supabase/migrations/20261020120000_signal_rules.sql.

The JSON (SignalRule[], camelCase) is the single source of the T1 rules: the engine tests import it and
this script turns it into the migration (table + RLS + seed). Usage: python3 scripts/ml/signal_rules_sql.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "web" / "src" / "backend" / "fixtures" / "t1-signal-rules.json"
DST = ROOT / "supabase" / "migrations" / "20261020120000_signal_rules.sql"


def lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


rules = json.loads(SRC.read_text(encoding="utf-8"))
values = ",\n  ".join(
    f"({lit(r['code'])}, {lit(r['label'])}, {lit(json.dumps(r['match'], separators=(',', ':')))}::jsonb, "
    f"{r['strength']}, {r['windowDays']}, {r['halfLifeDays']}, {'true' if r['isDisruption'] else 'false'})"
    for r in rules
)

DST.write_text(f"""-- T1 · signal_rules: how events become signals (backend/T1-signals-context.md).
-- Generated by scripts/ml/signal_rules_sql.py from web/src/backend/fixtures/t1-signal-rules.json — edit the JSON.
-- `match` has the shape of SignalRule.match in web/src/backend/types.ts:
--   {{ kind: "page_view|simulation" | "tx:<category>" | "profile:<kind>" | "partner:<status>" | "pattern:<name>",
--     sourceRows?: number[], detail?: Condition, textAny?: string[] }}

create table public.signal_rules (
  code text primary key,
  label text not null,
  match jsonb not null check (jsonb_typeof(match) = 'object' and match ? 'kind'),
  strength numeric(4, 3) not null check (strength > 0 and strength <= 1),
  window_days int not null check (window_days > 0),
  half_life_days int not null check (half_life_days > 0),
  is_disruption boolean not null default false
);

-- Config table: readable by everyone (non-sensitive), written only through migrations.
alter table public.signal_rules enable row level security;
create policy "signal rules are readable" on public.signal_rules
  for select to anon, authenticated using (true);
revoke insert, update, delete, truncate on public.signal_rules from anon, authenticated;

insert into public.signal_rules (code, label, match, strength, window_days, half_life_days, is_disruption) values
  {values}
on conflict (code) do update set label = excluded.label, match = excluded.match, strength = excluded.strength,
  window_days = excluded.window_days, half_life_days = excluded.half_life_days, is_disruption = excluded.is_disruption;
""", encoding="utf-8")
print(f"wrote {DST.relative_to(ROOT)} ({len(rules)} rules)")
