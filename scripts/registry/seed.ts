// Generate supabase/seed/capabilities.sql from the T4 registry data (web/src/backend/fixtures/t4-rules.ts).
// Usage, from the repo root: node scripts/registry/seed.ts   (Node >= 23.6 runs TypeScript natively)
// The seed replaces every registry row in one transaction, so it can be re-run after any edit.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { t4Rules } from "../../web/src/backend/fixtures/t4-rules.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = join(root, "supabase", "seed", "capabilities.sql");

const str = (v: string): string => `'${v.replaceAll("'", "''")}'`;
const num = (v: number | null): string => (v === null ? "null" : String(v));
const json = (v: unknown): string => (v === null || v === undefined ? "null" : `${str(JSON.stringify(v))}::jsonb`);
const textArray = (v: string[]): string => `array[${v.map(str).join(", ")}]::text[]`;
const rows = (lines: string[]): string => lines.map((l) => `  ${l}`).join(",\n");

const { capabilities, providers, templates } = t4Rules;

const sql = `-- Generated by scripts/registry/seed.ts from web/src/backend/fixtures/t4-rules.ts. Do not edit by hand.
begin;

delete from public.template_steps;
delete from public.goal_templates;
delete from public.capability_providers;
delete from public.capabilities;

insert into public.capabilities (code, label, ecosystem, what_it_solves, required_data, output) values
${rows(capabilities.map((c) => `(${str(c.code)}, ${str(c.label)}, ${str(c.ecosystem)}, ${str(c.whatItSolves)}, ${textArray(c.requiredData)}, ${str(c.output)})`))};

insert into public.capability_providers (capability_code, source_row, lead_time_days, cost_eur, priority, estimates) values
${rows(providers.map((p) => `(${str(p.capability)}, ${p.sourceRow}, ${p.leadTimeDays}, ${num(p.costEur)}, ${p.priority}, ${json(p.estimates)})`))};

insert into public.goal_templates (goal_type, label, default_constraints, outcome) values
${rows(templates.map((t) => `(${str(t.goalType)}, ${str(t.label)}, ${json(t.defaultConstraints)}, ${str(t.outcome)})`))};

insert into public.template_steps (goal_type, capability_code, chapter, position, depends_on, condition, why, optional) values
${rows(
  templates.flatMap((t) =>
    t.steps.map(
      (s) =>
        `(${str(s.goalType)}, ${str(s.capability)}, ${str(s.chapter)}, ${s.position}, ${textArray(s.dependsOn)}, ${json(s.condition)}, ${str(s.why)}, ${s.optional})`,
    ),
  ),
)};

commit;
`;

writeFileSync(out, sql);
console.log(
  `${capabilities.length} capabilities, ${providers.length} providers, ${templates.length} templates, ` +
    `${templates.reduce((n, t) => n + t.steps.length, 0)} steps -> ${out}`,
);
